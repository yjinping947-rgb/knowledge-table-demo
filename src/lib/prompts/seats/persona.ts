// 三席位的完整人设。接通 LLM 后，这里是回答质量的主要来源。
//
// 设计原则：光有"立场"不够，还要有"边界"—— 明确写出这个席位"不说什么"，
// 模型才不会一路滑向极端（比如把裸辞说成唯一答案）。

import type { SeatId } from "@/lib/types";

